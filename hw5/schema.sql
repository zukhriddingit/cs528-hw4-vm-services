-- CS 528 HW5: PostgreSQL schema.
-- All requests, including unsuccessful requests, are recorded here.
CREATE TABLE IF NOT EXISTS requests (
    request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country TEXT,
    client_ip INET,
    gender VARCHAR(16),
    age VARCHAR(16),
    income VARCHAR(16),
    is_banned BOOLEAN NOT NULL,
    time_of_day TIMESTAMP WITHOUT TIME ZONE,
    requested_file TEXT NOT NULL,
    status_code SMALLINT NOT NULL,
    received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Failed requests contain only the three requested event fields,
-- plus a surrogate key required to define a reliable primary key.
CREATE TABLE IF NOT EXISTS failed_requests (
    failure_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    requested_file TEXT NOT NULL,
    error_code SMALLINT NOT NULL CHECK (error_code <> 200)
);
