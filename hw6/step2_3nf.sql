-- CS528 Homework 6: normalized, lossless 3NF copy of the HW5 schema.
-- This file is executed statement by statement in ONE transaction by step2_migrate.py.
-- Source tables requests and failed_requests are never altered or deleted.
-- Each -- HW6-SQL-SPLIT line marks a statement boundary for the runner.
--
-- Functional dependencies on valid course data:
--     client_ip -> country
--     country   -> is_banned
-- A small amount of inconsistent legacy data violates the first dependency.
-- Exceptions are kept separately, rather than discarded or silently relabeled.

CREATE TABLE IF NOT EXISTS hw6_countries (
    country_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country TEXT NOT NULL UNIQUE,
    is_banned BOOLEAN NOT NULL
);

-- HW6-SQL-SPLIT
CREATE TABLE IF NOT EXISTS hw6_ip_country (
    client_ip INET PRIMARY KEY,
    country_id INTEGER REFERENCES hw6_countries(country_id)
);

-- HW6-SQL-SPLIT
CREATE TABLE IF NOT EXISTS hw6_requests (
    request_id BIGINT PRIMARY KEY,
    client_ip INET NOT NULL REFERENCES hw6_ip_country(client_ip),
    gender VARCHAR(16),
    age VARCHAR(16),
    income VARCHAR(16),
    time_of_day TIMESTAMP WITHOUT TIME ZONE,
    requested_file TEXT NOT NULL,
    status_code SMALLINT NOT NULL,
    received_at TIMESTAMPTZ NOT NULL
);

-- HW6-SQL-SPLIT
CREATE TABLE IF NOT EXISTS hw6_request_country_exceptions (
    request_id BIGINT PRIMARY KEY REFERENCES hw6_requests(request_id),
    -- NULL means the legacy request itself had no country.
    original_country_id INTEGER REFERENCES hw6_countries(country_id)
);

-- HW6-SQL-SPLIT
-- Rebuilding these derived tables is transactional and repeatable.
-- The original requests/failed_requests tables are NOT referenced by TRUNCATE.
TRUNCATE TABLE
    hw6_request_country_exceptions,
    hw6_requests,
    hw6_ip_country,
    hw6_countries
RESTART IDENTITY;

-- HW6-SQL-SPLIT
-- One row per country; country -> is_banned was checked in preflight.
INSERT INTO hw6_countries (country, is_banned)
SELECT country, BOOL_OR(is_banned)
FROM requests
WHERE country IS NOT NULL
GROUP BY country
ORDER BY country;

-- HW6-SQL-SPLIT
-- IPs map to a single canonical country, using the most frequently observed
-- country per IP. An exact tie is broken deterministically by country name.
WITH ip_frequencies AS (
    SELECT client_ip, country, COUNT(*) AS n
    FROM requests
    GROUP BY client_ip, country
),
ranked AS (
    SELECT
        client_ip,
        country,
        ROW_NUMBER() OVER (
            PARTITION BY client_ip
            ORDER BY n DESC, country ASC NULLS LAST
        ) AS rn
    FROM ip_frequencies
)
INSERT INTO hw6_ip_country (client_ip, country_id)
SELECT ranked.client_ip, dim.country_id
FROM ranked
LEFT JOIN hw6_countries AS dim ON dim.country = ranked.country
WHERE ranked.rn = 1;

-- HW6-SQL-SPLIT
-- Facts contain request-specific attributes only. Country/ban are NOT repeated.
INSERT INTO hw6_requests (
    request_id, client_ip, gender, age, income,
    time_of_day, requested_file, status_code, received_at
)
SELECT
    request_id, client_ip, gender, age, income,
    time_of_day, requested_file, status_code, received_at
FROM requests;

-- HW6-SQL-SPLIT
-- Preserve the EXACT original country of anomalous requests in a sparse table.
-- This also preserves NULL vs non-NULL country values. On clean requests,
-- the country is obtained solely through the IP table.
INSERT INTO hw6_request_country_exceptions (request_id, original_country_id)
SELECT raw.request_id, original_dim.country_id
FROM requests AS raw
JOIN hw6_ip_country AS ip ON raw.client_ip = ip.client_ip
LEFT JOIN hw6_countries AS original_dim ON original_dim.country = raw.country
WHERE ip.country_id IS DISTINCT FROM original_dim.country_id;

-- HW6-SQL-SPLIT
CREATE INDEX IF NOT EXISTS hw6_requests_income_idx ON hw6_requests (income);

-- HW6-SQL-SPLIT
CREATE INDEX IF NOT EXISTS hw6_requests_received_at_idx ON hw6_requests (received_at);

